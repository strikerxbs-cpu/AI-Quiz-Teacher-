/* =========================================================
   QUIZ ENGINE
   ========================================================= */

let currentSubject = "bangla";
let quizQuestions = [];
let currentIndex = 0;
let correctCount = 0;
let wrongCount = 0;
let answered = false;
let quizTotal = 10;


/* ---------- Voice ---------- */

function speakText(text) {

  if (!("speechSynthesis" in window)) {
    return;
  }

  try {
    window.speechSynthesis.cancel();

    const speech = new SpeechSynthesisUtterance(text);

    speech.lang = "bn-BD";
    speech.rate = 0.9;
    speech.pitch = 1;
    speech.volume = 1;

    const voices = window.speechSynthesis.getVoices();

    const banglaVoice = voices.find(v =>
      v.lang && v.lang.toLowerCase().startsWith("bn")
    );

    if (banglaVoice) {
      speech.voice = banglaVoice;
    }

    window.speechSynthesis.speak(speech);

  } catch (error) {
    console.log("Voice error:", error);
  }
}


window.speechSynthesis &&
window.speechSynthesis.addEventListener(
  "voiceschanged",
  function () {
    window.speechSynthesis.getVoices();
  }
);


/* ---------- Subject ---------- */

function getSelectedSubject() {

  const select = document.getElementById("subjectSelect");

  if (!select) {
    return "bangla";
  }

  return select.value || "bangla";
}


/* ---------- Start Quiz ---------- */

function startQuiz(number) {

  currentSubject = getSelectedSubject();

  const bank = questions[currentSubject];

  if (!bank || bank.length === 0) {
    alert("এই বিষয়ে প্রশ্ন পাওয়া যায়নি।");
    return;
  }

  quizTotal = Math.min(Number(number) || 10, bank.length);

  quizQuestions = [...bank]
    .sort(() => Math.random() - 0.5)
    .slice(0, quizTotal);

  currentIndex = 0;
  correctCount = 0;
  wrongCount = 0;
  answered = false;

  showQuizArea();

  showQuestion();

}


/* ---------- Show Quiz ---------- */

function showQuizArea() {

  const quiz = document.getElementById("quiz");

  if (quiz) {
    quiz.style.display = "block";
  }

  const result = document.querySelector(".result-card");

  if (result) {
    result.style.display = "none";
  }

  const explanation = document.getElementById("explanation");

  if (explanation) {
    explanation.style.display = "none";
  }

  const nextButton = document.getElementById("nextQuestion");

  if (nextButton) {
    nextButton.style.display = "none";
  }
}


/* ---------- Show Question ---------- */

function showQuestion() {

  if (currentIndex >= quizQuestions.length) {
    finishQuiz();
    return;
  }

  answered = false;

  const item = quizQuestions[currentIndex];

  const questionElement =
    document.getElementById("question");

  const numberElement =
    document.getElementById("questionNumber");

  const optionsElement =
    document.getElementById("options");

  const explanation =
    document.getElementById("explanation");

  const explanationText =
    document.getElementById("explanationText");

  if (questionElement) {
    questionElement.textContent = item[0];
  }

  if (numberElement) {
    numberElement.textContent =
      `প্রশ্ন ${currentIndex + 1} / ${quizTotal}`;
  }

  if (explanation) {
    explanation.style.display = "none";
  }

  if (explanationText) {
    explanationText.textContent = "";
  }

  if (!optionsElement) {
    return;
  }

  optionsElement.innerHTML = "";

  item[1].forEach((option, index) => {

    const button = document.createElement("button");

    button.className = "option-btn";

    button.textContent = option;

    button.type = "button";

    button.onclick = function () {
      checkAnswer(index, button);
    };

    optionsElement.appendChild(button);

  });

  updateScore();

}


/* ---------- Check Answer ---------- */

function checkAnswer(selected, clickedButton) {

  if (answered) {
    return;
  }

  answered = true;

  const item = quizQuestions[currentIndex];

  const correctAnswer = item[2];

  const buttons =
    document.querySelectorAll("#options button");

  buttons.forEach(btn => {
    btn.disabled = true;
  });

  if (selected === correctAnswer) {

    correctCount++;

    clickedButton.classList.add("correct");

    showFeedback(
      "সঠিক হয়েছে! ✅",
      item[3]
    );

    speakText("সঠিক হয়েছে!");

  } else {

    wrongCount++;

    clickedButton.classList.add("wrong");

    if (buttons[correctAnswer]) {
      buttons[correctAnswer].classList.add("correct");
    }

    showFeedback(
      "ভুল হয়েছে! ❌",
      "সঠিক উত্তর: " +
      item[1][correctAnswer] +
      "। " +
      item[3]
    );

    speakText(
      "ভুল হয়েছে। সঠিক উত্তর হলো " +
      item[1][correctAnswer]
    );

  }

  updateScore();

  /* নিজে নিজে পরের প্রশ্নে যাবে */
  setTimeout(function () {

    currentIndex++;

    showQuestion();

  }, 1800);

}


/* ---------- Feedback ---------- */

function showFeedback(title, explanationTextValue) {

  const explanation =
    document.getElementById("explanation");

  const text =
    document.getElementById("explanationText");

  if (explanation) {
    explanation.style.display = "block";
  }

  if (text) {
    text.textContent =
      title + " " + explanationTextValue;
  }

}


/* ---------- Score ---------- */

function updateScore() {

  const score =
    document.getElementById("scoreDisplay");

  if (score) {
    score.textContent =
      `সঠিক: ${correctCount} | ভুল: ${wrongCount}`;
  }

  const correct =
    document.getElementById("correctCount");

  if (correct) {
    correct.textContent = correctCount;
  }

  const wrong =
    document.getElementById("wrongCount");

  if (wrong) {
    wrong.textContent = wrongCount;
  }

}


/* ---------- Finish ---------- */

function finishQuiz() {

  const percentage =
    Math.round((correctCount / quizTotal) * 100);

  const resultCard =
    document.querySelector(".result-card");

  if (resultCard) {
    resultCard.style.display = "block";
  }

  const resultText =
    document.getElementById("resultText");

  if (resultText) {

    resultText.textContent =
      `তোমার স্কোর: ${correctCount} / ${quizTotal} (${percentage}%)`;

  }

  const scoreDisplay =
    document.getElementById("scoreDisplay");

  if (scoreDisplay) {

    scoreDisplay.textContent =
      `${correctCount} / ${quizTotal} — ${percentage}%`;

  }

  speakText(
    `কুইজ শেষ। তোমার স্কোর ${correctCount} এর মধ্যে ${quizTotal}। তুমি ${percentage} শতাংশ পেয়েছ।`
  );

}


/* ---------- Restart ---------- */

function restartQuiz() {

  const result =
    document.querySelector(".result-card");

  if (result) {
    result.style.display = "none";
  }

  startQuiz(quizTotal);

}


/* ---------- Manual Next Support ---------- */

function nextQuestion() {

  if (!answered) {
    return;
  }

  currentIndex++;

  showQuestion();

}


