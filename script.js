/* =========================================
   SHUFFLE QUESTIONS
   ========================================= */

function shuffleArray(array) {

    for (
        let i = array.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() * (i + 1)
            );

        [
            array[i],
            array[j]
        ] =
        [
            array[j],
            array[i]
        ];
    }

    return array;
}


/* =========================================
   VOICE
   ========================================= */

function speakText(text) {

    if (
        !("speechSynthesis" in window)
    ) {
        return;
    }

    /*
     * আগের voice বন্ধ করবে।
     */

    window.speechSynthesis.cancel();

    const speech =
        new SpeechSynthesisUtterance(text);

    speech.lang = "bn-BD";

    speech.rate = 0.9;

    speech.pitch = 1;

    speech.volume = 1;


    /*
     * বাংলা Voice খুঁজে নেওয়া
     */

    const voices =
        window.speechSynthesis
        .getVoices();

    const banglaVoice =
        voices.find(function (voice) {

            return (
                voice.lang &&
                voice.lang
                    .toLowerCase()
                    .startsWith("bn")
            );

        });


    if (banglaVoice) {

        speech.voice =
            banglaVoice;
    }


    window.speechSynthesis
        .speak(speech);
}


