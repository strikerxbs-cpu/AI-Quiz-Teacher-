/* =========================================
   START QUIZ
   ========================================= */

function startQuiz(count) {

    selectedSubject =
        document.getElementById("subjectSelect").value;

    questionLimit = count;

    const allQuestions =
        questions[selectedSubject];

    if (!allQuestions ||
        allQuestions.length === 0) {

        alert("এই বিষয়ে প্রশ্ন পাওয়া যায়নি।");
        return;
    }

    /*
     * ১০/২০/৩০/৬০ প্রশ্ন নির্বাচন
     */

    quizQuestions =
        shuffleArray([...allQuestions])
        .slice(
            0,
            Math.min(count, allQuestions.length)
        );

    currentQuestion = 0;
    score = 0;
    answered = false;

    const resultSection =
        document.getElementById("resultSection");

    if (resultSection) {
        resultSection.style.display = "none";
    }

    document.getElementById("score").innerText =
        "স্কোর: ০";

    /*
     * Quiz section দেখানো
     */

    const quizSection =
        document.getElementById("quizSection");

    quizSection.style.display = "block";

    /*
     * এখানে পেজকে উপরে পাঠানো হবে না।
     * শুধু Quiz-এর দিকে smooth scroll করবে।
     */

    quizSection.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

    showQuestion();
}


/* =========================================
   SHOW QUESTION
   ========================================= */

function showQuestion() {

    answered = false;

    const q =
        quizQuestions[currentQuestion];

    if (!q) return;

    document.getElementById("questionNumber")
        .innerText =
        "প্রশ্ন " +
        (currentQuestion + 1) +
        " / " +
        quizQuestions.length;

    document.getElementById("questionText")
        .innerText =
        q[0];

    document.getElementById("feedback")
        .innerText = "";

    document.getElementById("feedback")
        .className = "feedback";

    document.getElementById("nextMessage")
        .innerText = "";

    document.getElementById("teacherText")
        .innerText =
        "একটি উত্তর নির্বাচন করো।";

    const answers =
        document.getElementById("answers");

    answers.innerHTML = "";

    q[1].forEach(function (answer, index) {

        const button =
            document.createElement("button");

        button.type = "button";

        button.innerText =
            answer;

        /*
         * onclick-এর বদলে addEventListener।
         * তাই পেজ উপরে যাবে না।
         */

        button.addEventListener(
            "click",
            function (event) {

                event.preventDefault();

                checkAnswer(index);

            }
        );

        answers.appendChild(button);
    });
}


/* =========================================
   CHECK ANSWER
   ========================================= */

function checkAnswer(selectedIndex) {

    if (answered) return;

    answered = true;

    const q =
        quizQuestions[currentQuestion];

    const correctIndex =
        q[2];

    const buttons =
        document.querySelectorAll(
            "#answers button"
        );

    buttons.forEach(function (button, index) {

        button.disabled = true;

        if (index === correctIndex) {
            button.classList.add("correct");
        }

        if (
            index === selectedIndex &&
            selectedIndex !== correctIndex
        ) {
            button.classList.add("wrong");
        }

    });


    const feedback =
        document.getElementById("feedback");

    const teacher =
        document.getElementById("teacherText");


    if (selectedIndex === correctIndex) {

        score++;

        document.getElementById("score")
            .innerText =
            "স্কোর: " + score;

        feedback.innerText =
            "✅ সঠিক হয়েছে!";

        feedback.className =
            "feedback correct";

        teacher.innerText =
            "দারুণ! তোমার উত্তর সঠিক হয়েছে।";

        /*
         * Voice
         */

        speakText(
            "সঠিক হয়েছে। খুব ভালো!"
        );

    } else {

        feedback.innerText =
            "❌ ভুল হয়েছে! সঠিক উত্তর: " +
            q[1][correctIndex];

        feedback.className =
            "feedback wrong";

        teacher.innerText =
            "উত্তরটি সঠিক নয়। সঠিক উত্তর হলো " +
            q[1][correctIndex];

        /*
         * Voice
         */

        speakText(
            "ভুল হয়েছে। সঠিক উত্তর হলো " +
            q[1][correctIndex]
        );
    }


    /*
     * ১.৮ সেকেন্ড পর নিজে থেকেই
     * পরের প্রশ্নে যাবে।
     */

    document.getElementById("nextMessage")
        .innerText =
        "➡️ পরের প্রশ্ন আসছে...";

    setTimeout(function () {

        if (
            currentQuestion <
            quizQuestions.length - 1
        ) {

            currentQuestion++;

            showQuestion();

        } else {

            finishQuiz();

        }

    }, 1800);
}


/* =========================================
   FINISH QUIZ
   ========================================= */

function finishQuiz() {

    const total =
        quizQuestions.length;

    const wrong =
        total - score;

    const percentage =
        Math.round(
            (score / total) * 100
        );


    document.getElementById("correctCount")
        .innerText =
        score;

    document.getElementById("wrongCount")
        .innerText =
        wrong;

    document.getElementById("percentage")
        .innerText =
        percentage + "%";

    document.getElementById("finalScore")
        .innerText =
        "তোমার স্কোর: " +
        score +
        " / " +
        total;


    const result =
        document.getElementById("resultSection");

    result.style.display =
        "block";


    let message = "";

    if (percentage >= 80) {

        message =
            "অসাধারণ! তুমি খুব ভালো করেছো।";

    } else if (percentage >= 60) {

        message =
            "খুব ভালো! আরও একটু অনুশীলন করো।";

    } else {

        message =
            "ভালো চেষ্টা! আবার অনুশীলন করো।";
    }


    speakText(
        "কুইজ শেষ হয়েছে। " +
        "তোমার স্কোর " +
        score +
        " এর মধ্যে " +
        total +
        "। " +
        message
    );


    result.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });
}


